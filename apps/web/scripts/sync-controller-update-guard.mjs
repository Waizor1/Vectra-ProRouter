#!/usr/bin/env node
// Regenerates src/lib/controller-update-guard-script.ts from the canonical
// router/vectra-controller-agent/openwrt/update-guard/vectra-update-guard.sh.
// The self-update command embeds the guard verbatim; comment and blank lines
// and leading indentation are dropped so it fits the terminal-command budget.
//
//   node apps/web/scripts/sync-controller-update-guard.mjs          # write
//   node apps/web/scripts/sync-controller-update-guard.mjs --check  # verify

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const source = path.resolve(
  here,
  "../../../router/vectra-controller-agent/openwrt/update-guard/vectra-update-guard.sh",
);
const target = path.resolve(here, "../src/lib/controller-update-guard-script.ts");

/** @param {string} text @returns {string} */
export function compactGuardScript(text) {
  return text
    .split("\n")
    .map((/** @type {string} */ line) => line.replace(/^[\t ]+/, ""))
    .filter((/** @type {string} */ line, /** @type {number} */ index) => {
      if (index === 0 && line.startsWith("#!")) return true;
      return line.length > 0 && !line.startsWith("#");
    })
    .join("\n");
}

/** @param {string} text @returns {string} */
export function renderGuardModule(text) {
  return [
    "// GENERATED by apps/web/scripts/sync-controller-update-guard.mjs from",
    "// router/vectra-controller-agent/openwrt/update-guard/vectra-update-guard.sh.",
    "// Do not edit: change the .sh and re-run the script.",
    `export const controllerUpdateGuardScript = ${JSON.stringify(compactGuardScript(text))};`,
    "",
  ].join("\n");
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const rendered = renderGuardModule(readFileSync(source, "utf8"));
  if (process.argv.includes("--check")) {
    const current = readFileSync(target, "utf8");
    if (current !== rendered) {
      console.error(`${target} is stale: run node apps/web/scripts/sync-controller-update-guard.mjs`);
      process.exit(1);
    }
  } else {
    writeFileSync(target, rendered);
  }
}
